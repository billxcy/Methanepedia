const I18N_ATTRIBUTE_NAMES = ["aria-label", "alt", "title", "placeholder", "content"];
const I18N_LANGUAGE_KEY = "methanepedia-language";
const I18N_ORIGINAL_TEXT = new WeakMap();
const I18N_ORIGINAL_ATTRIBUTES = new WeakMap();
let i18nDocumentTitle = null;
let i18nIsApplying = false;
let i18nObserver = null;

const getStoredLanguage = () => {
    try {
        return localStorage.getItem(I18N_LANGUAGE_KEY) === "en" ? "en" : "zh";
    } catch (_) {
        return "zh";
    }
};

const storeLanguage = (language) => {
    try {
        localStorage.setItem(I18N_LANGUAGE_KEY, language);
    } catch (_) {
        // Language persistence is optional; the toggle still works in-memory.
    }
};

const translateCoreText = (text) => {
    if (METHANEPEDIA_TRANSLATIONS[text]) {
        return METHANEPEDIA_TRANSLATIONS[text];
    }

    let translated = text;
    const dynamicReplacements = [
        ["基准情景 (NDC)", "Baseline scenario (NDC)"],
        ["减排情景 (NZE)", "Mitigation scenario (NZE)"],
        ["百万吨/年", "Mt/year"],
        ["数据来源：", "Data source: "]
    ];

    dynamicReplacements.forEach(([source, target]) => {
        translated = translated.split(source).join(target);
    });

    return translated;
};

const translatePreservingWhitespace = (value, language) => {
    if (language === "zh" || typeof value !== "string") return value;

    const leading = value.match(/^\s*/)?.[0] || "";
    const trailing = value.match(/\s*$/)?.[0] || "";
    const core = value.trim();
    if (!core) return value;

    const translated = translateCoreText(core);
    return translated === core ? value : `${leading}${translated}${trailing}`;
};

const shouldSkipTranslation = (node) => {
    const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
    return Boolean(element?.closest("script, style, noscript, [data-no-translate]"));
};

const translateTextNode = (node, language) => {
    if (shouldSkipTranslation(node)) return;
    if (!I18N_ORIGINAL_TEXT.has(node)) {
        I18N_ORIGINAL_TEXT.set(node, node.nodeValue);
    }
    const original = I18N_ORIGINAL_TEXT.get(node);
    node.nodeValue = translatePreservingWhitespace(original, language);
};

const getOriginalAttributeValue = (element, attributeName) => {
    let store = I18N_ORIGINAL_ATTRIBUTES.get(element);
    if (!store) {
        store = {};
        I18N_ORIGINAL_ATTRIBUTES.set(element, store);
    }
    if (!(attributeName in store)) {
        store[attributeName] = element.getAttribute(attributeName);
    }
    return store[attributeName];
};

const translateElementAttributes = (element, language) => {
    if (shouldSkipTranslation(element)) return;

    I18N_ATTRIBUTE_NAMES.forEach((attributeName) => {
        if (!element.hasAttribute(attributeName)) return;
        const original = getOriginalAttributeValue(element, attributeName);
        element.setAttribute(attributeName, translatePreservingWhitespace(original, language));
    });
};

const translateTree = (root, language) => {
    if (!root || shouldSkipTranslation(root)) return;

    if (root.nodeType === Node.TEXT_NODE) {
        translateTextNode(root, language);
        return;
    }

    if (root.nodeType === Node.ELEMENT_NODE) {
        translateElementAttributes(root, language);
    }

    const walker = document.createTreeWalker(
        root,
        NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT,
        {
            acceptNode(node) {
                return shouldSkipTranslation(node) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    let node = walker.nextNode();
    while (node) {
        if (node.nodeType === Node.TEXT_NODE) {
            translateTextNode(node, language);
        } else if (node.nodeType === Node.ELEMENT_NODE) {
            translateElementAttributes(node, language);
        }
        node = walker.nextNode();
    }
};

const translateDocumentMeta = (language) => {
    if (i18nDocumentTitle === null) {
        i18nDocumentTitle = document.title;
    }
    document.title = translatePreservingWhitespace(i18nDocumentTitle, language);

    document.querySelectorAll("meta[name='description']").forEach((meta) => {
        const original = getOriginalAttributeValue(meta, "content");
        meta.setAttribute("content", translatePreservingWhitespace(original, language));
    });
};

const updateLanguageToggle = (button, language) => {
    if (!button) return;
    const isEnglish = language === "en";
    button.textContent = isEnglish ? "中文" : "EN";
    button.setAttribute("aria-label", isEnglish ? "切换到中文" : "Switch to English");
    button.setAttribute("title", isEnglish ? "切换到中文" : "Switch to English");
    button.setAttribute("aria-pressed", String(isEnglish));
};

const applyLanguage = (language, button) => {
    i18nIsApplying = true;
    document.documentElement.lang = language === "en" ? "en" : "zh-CN";
    document.documentElement.classList.toggle("lang-en", language === "en");
    translateDocumentMeta(language);
    translateTree(document.body, language);
    updateLanguageToggle(button || document.querySelector("[data-language-toggle]"), language);
    window.setTimeout(() => {
        i18nIsApplying = false;
    }, 0);
};

const observeLanguageMutations = (getLanguage) => {
    if (i18nObserver) {
        i18nObserver.disconnect();
    }

    i18nObserver = new MutationObserver((mutations) => {
        if (i18nIsApplying || getLanguage() !== "en") return;
        mutations.forEach((mutation) => {
            if (mutation.type === "characterData") {
                translateTextNode(mutation.target, "en");
                return;
            }
            mutation.addedNodes.forEach((node) => translateTree(node, "en"));
        });
    });

    i18nObserver.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true
    });
};

const initLanguageSwitcher = (siteNav, navToggle) => {
    let currentLanguage = getStoredLanguage();
    let button = siteNav?.querySelector("[data-language-toggle]");

    if (siteNav && !button) {
        button = document.createElement("button");
        button.className = "language-toggle";
        button.type = "button";
        button.dataset.languageToggle = "true";
        button.dataset.noTranslate = "true";
        siteNav.appendChild(button);
    }

    updateLanguageToggle(button, currentLanguage);

    button?.addEventListener("click", () => {
        currentLanguage = currentLanguage === "en" ? "zh" : "en";
        storeLanguage(currentLanguage);
        applyLanguage(currentLanguage, button);
        siteNav?.classList.remove("is-open");
        navToggle?.setAttribute("aria-expanded", "false");
        document.body.classList.remove("nav-open");
    });

    applyLanguage(currentLanguage, button);
    observeLanguageMutations(() => currentLanguage);
};

const initDataDetailExplorers = () => {
    document.querySelectorAll("[data-detail-explorer]").forEach((explorer) => {
        const triggers = Array.from(explorer.querySelectorAll("[data-detail-trigger]"));
        const panels = Array.from(explorer.querySelectorAll(".data-detail-panel, [data-detail-panel]"));
        const placeholder = explorer.querySelector("[data-detail-placeholder]");

        const openPanel = (trigger) => {
            const panel = panels.find((candidate) => candidate.id === trigger.dataset.detailTrigger);
            if (!panel) return;

            triggers.forEach((candidate) => {
                const isActive = candidate === trigger;
                candidate.classList.toggle("is-active", isActive);
                candidate.setAttribute("aria-expanded", String(isActive));
            });

            panels.forEach((candidate) => {
                const isActive = candidate === panel;
                candidate.hidden = !isActive;
                candidate.classList.toggle("is-open", isActive);
            });

            if (placeholder) {
                placeholder.hidden = true;
            }
        };

        triggers.forEach((trigger) => {
            trigger.addEventListener("click", () => openPanel(trigger));
        });

        const activeTrigger = triggers.find((trigger) => trigger.classList.contains("is-active"));
        if (activeTrigger) {
            openPanel(activeTrigger);
        }
    });
};

document.addEventListener("DOMContentLoaded", () => {
    const navToggle = document.querySelector(".nav-toggle");
    const siteNav = document.querySelector(".site-nav");
    const progressFill = document.getElementById("scrollProgressFill");

    initLanguageSwitcher(siteNav, navToggle);
    initDataDetailExplorers();

    if (navToggle && siteNav) {
        navToggle.addEventListener("click", () => {
            const isOpen = siteNav.classList.toggle("is-open");
            navToggle.setAttribute("aria-expanded", String(isOpen));
            document.body.classList.toggle("nav-open", isOpen);
        });

        siteNav.querySelectorAll("a").forEach((link) => {
            link.addEventListener("click", () => {
                siteNav.classList.remove("is-open");
                navToggle.setAttribute("aria-expanded", "false");
                document.body.classList.remove("nav-open");
            });
        });
    }

    const updateProgress = () => {
        if (!progressFill) return;
        const scrollable = document.documentElement.scrollHeight - window.innerHeight;
        const progress = scrollable > 0 ? Math.min(100, Math.max(0, (window.scrollY / scrollable) * 100)) : 0;
        progressFill.style.width = `${progress}%`;
    };

    updateProgress();
    window.addEventListener("scroll", updateProgress, { passive: true });
    window.addEventListener("resize", updateProgress);

    const carousel = document.querySelector("[data-carousel]");
    if (carousel) {
        const slides = carousel.querySelector(".carousel-slides");
        const items = Array.from(carousel.querySelectorAll(".slide"));
        const previous = document.querySelector("[data-carousel-prev]");
        const next = document.querySelector("[data-carousel-next]");
        let activeIndex = 0;
        let autoplayId;

        const showSlide = (index) => {
            if (!slides || items.length === 0) return;
            activeIndex = (index + items.length) % items.length;
            slides.style.transform = `translateX(-${activeIndex * 100}%)`;
        };

        const startAutoplay = () => {
            if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
            autoplayId = window.setInterval(() => showSlide(activeIndex + 1), 6500);
        };

        const restartAutoplay = () => {
            window.clearInterval(autoplayId);
            startAutoplay();
        };

        previous?.addEventListener("click", () => {
            showSlide(activeIndex - 1);
            restartAutoplay();
        });

        next?.addEventListener("click", () => {
            showSlide(activeIndex + 1);
            restartAutoplay();
        });

        carousel.addEventListener("mouseenter", () => window.clearInterval(autoplayId));
        carousel.addEventListener("mouseleave", startAutoplay);

        showSlide(0);
        startAutoplay();
    }
});
